"""Schema migration, applied at boot (T0.3).

REPLACES `Base.metadata.create_all`, which was never a migration tool and did
not pretend to be one: it creates MISSING TABLES and stops. It never adds a
column to an existing table, never widens a type, never makes a column nullable
— and it raises nothing when it skips one. models.py carries six separate
comments saying so, each of them written after the fact.

That was survivable while the database was disposable. It stops being survivable
with the variant work, which both adds tables AND changes an existing column
(price_aed_min becoming nullable), on an instance that may already hold real
customers, bookings and consent records.

THE ADOPTION PROBLEM, AND HOW THIS SOLVES IT. Every database that already exists
was built by create_all and therefore has all seventeen tables and NO
`alembic_version` row. Running `upgrade head` against one would try to CREATE
tables that are already there and fail on the first one. So:

    no revision, but tables present  ->  STAMP head (adopt in place)
    no revision, no tables           ->  UPGRADE head (fresh install)
    revision present                 ->  UPGRADE head (normal path)

THE TEST IS "NO REVISION", NOT "NO VERSION TABLE", and the difference is not
theoretical: this repo's own dev database was found holding an EMPTY
`alembic_version` table beside seventeen populated ones. An empty table is the
same state as no table — nothing has been applied — but a has_table() check
calls it managed, takes the upgrade path, and dies on "table vehicle_models
already exists". That was the original condition here and it would have failed
on the first real database it met.

Stamping is safe here for one specific, verified reason: the baseline revision
was autogenerated from the same metadata create_all uses, and the two were
compared table by table — columns, nullability, primary keys, foreign keys,
unique constraints and indexes all match. Stamping asserts "this database is
already at that revision", and for a create_all database that assertion is true.
If the baseline is ever edited, that stops being true and this shortcut becomes
a lie — which is why the baseline revision must be treated as immutable.

FAIL LOUD, NOT OPEN. Unlike services/salesforce.py or services/turn_trace.py,
this does NOT swallow its errors. A telemetry write that fails costs a
statistic; a migration that fails and is ignored costs a schema the code
disagrees with, which surfaces later as a column that is silently missing. If
this raises, the app must not come up.
"""

from __future__ import annotations

import logging
from pathlib import Path

from sqlalchemy import inspect

from app.db import Base, engine

log = logging.getLogger("app.migrate")

# backend/app/migrate.py -> backend/
_BACKEND_ROOT = Path(__file__).resolve().parent.parent
_ALEMBIC_INI = _BACKEND_ROOT / "alembic.ini"
_ALEMBIC_DIR = _BACKEND_ROOT / "alembic"


def _config():
    """Alembic Config pointing at this repo's migration directory.

    Built with absolute paths rather than relying on the process CWD: uvicorn is
    started from the container's WORKDIR, pytest from the repo root, and the CLI
    from wherever the operator happens to be standing.
    """
    from alembic.config import Config

    cfg = Config(str(_ALEMBIC_INI))
    cfg.set_main_option("script_location", str(_ALEMBIC_DIR))
    return cfg


def _current_revision(conn) -> str | None:
    """The revision this connection's database is stamped at.

    None covers BOTH "no alembic_version table" and "an alembic_version table
    with no row in it" — see the module docstring. Alembic's own
    MigrationContext makes no distinction, and neither should we.
    """
    from alembic.runtime.migration import MigrationContext

    if not inspect(conn).has_table("alembic_version"):
        return None
    return MigrationContext.configure(conn).get_current_revision()


def _has_application_tables(conn) -> bool:
    """Any table this application owns, ignoring alembic's own bookkeeping."""
    present = set(inspect(conn).get_table_names()) - {"alembic_version"}
    return bool(present & set(Base.metadata.tables))


def upgrade_to_head() -> None:
    """Bring the database to the latest revision. Adopts a pre-alembic DB."""
    from alembic import command

    cfg = _config()
    # ONE connection, held open ACROSS the alembic command — not opened, probed,
    # closed, and then re-opened by env.py. Two connections could disagree about
    # what the database looks like, and env.py would build its own from
    # app.config, ignoring whatever engine this module was pointed at. Passing it
    # through `attributes` is alembic's supported way to say "use mine".
    with engine.begin() as conn:
        cfg.attributes["connection"] = conn
        versioned = _current_revision(conn) is not None
        populated = _has_application_tables(conn)

        if not versioned and populated:
            # A create_all database. Adopt it where it stands rather than trying
            # to rebuild a schema it already has. See the module docstring.
            log.warning(
                "adopting a pre-migration database: stamping alembic head without "
                "running the baseline (its tables already exist)"
            )
            command.stamp(cfg, "head")
            return

        command.upgrade(cfg, "head")
    log.info("database is at alembic head")


def current_revision() -> str | None:
    """The revision this database is stamped at, or None if unmanaged."""
    with engine.connect() as conn:
        return _current_revision(conn)
