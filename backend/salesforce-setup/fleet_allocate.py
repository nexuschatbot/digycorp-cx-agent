#!/usr/bin/env python3
"""Allocate (or de-allocate) a vehicle model to a showroom, in BOTH stores.

Fleet placement lives on VehicleModel.showroom_ids and is already honoured by
catalogue.list_showrooms(vehicle_id=...) — the filter has existed since the data
model was written but has never fired, because every model currently lists every
showroom. This script makes it fire.

Fleet and slots MUST agree. If a model stops being stocked at a branch while its
slots remain, showroom_ids says "not here" and the slot table says "bookable" —
a worse defect than the one we are fixing. So this script always does both:

  1. removes (or adds) the showroom in VehicleModel.showroom_ids
  2. deletes that model's FUTURE slots at that branch, in the app database
  3. deletes the matching Slot__c records in Salesforce

It REFUSES to run if any booking references a slot it would delete.

Usage, inside the backend container:
    docker exec -e SF_DOMAIN -e SF_CK -e SF_CS elite-backend-1 \
        python3 /tmp/fleet_allocate.py --model JET-G700 --showroom Deira --remove

Dry-run by default; add CONFIRM=1 to apply. To reverse, re-run with --add
(slots are then regenerated by `python -m app.cli generate-slots`).
"""
import argparse, json, os, sys, urllib.request, urllib.parse, urllib.error
from datetime import datetime

import psycopg

ap = argparse.ArgumentParser()
ap.add_argument("--model", required=True, help="model_code, e.g. JET-G700")
ap.add_argument("--showroom", required=True, help="showroom name fragment, e.g. Deira")
g = ap.add_mutually_exclusive_group(required=True)
g.add_argument("--remove", action="store_true")
g.add_argument("--add", action="store_true")
args = ap.parse_args()

CONFIRM = os.environ.get("CONFIRM") == "1"
DSN = os.environ["DATABASE_URL"].replace("+psycopg", "")
API = os.environ.get("SF_API_VERSION", "v62.0")

print(f"model={args.model}  showroom~{args.showroom}  action={'remove' if args.remove else 'add'}")
print("mode:", "APPLY" if CONFIRM else "DRY-RUN (set CONFIRM=1 to apply)")

conn = psycopg.connect(DSN)
row = conn.execute("SELECT id, name, showroom_ids FROM vehicle_models WHERE model_code = %s",
                   (args.model,)).fetchone()
if not row:
    sys.exit(f"ERROR: no vehicle with model_code {args.model}")
vid, vname, sids = row
sids = [int(x) for x in (sids or [])]

sh = conn.execute("SELECT id, name FROM showrooms WHERE name ILIKE %s",
                  (f"%{args.showroom}%",)).fetchall()
if len(sh) != 1:
    sys.exit(f"ERROR: showroom '{args.showroom}' matched {len(sh)} rows: {sh}")
sid, sname = sh[0]

print(f"\n{vname} (vehicle {vid}) currently at showroom_ids {sids}")
print(f"target: {sname} (showroom {sid})")

new_sids = [x for x in sids if x != sid] if args.remove else sorted(set(sids + [sid]))
if new_sids == sids:
    print("Nothing to change — already in the desired state.")
    sys.exit(0)
print(f"showroom_ids: {sids}  ->  {new_sids}")

# ---- safety: never orphan a booking ---------------------------------------- #
booked = conn.execute(
    """SELECT b.ref, b.status, s.start FROM bookings b JOIN slots s ON s.id = b.slot_id
       WHERE s.vehicle_id = %s AND s.showroom_id = %s""", (vid, sid)).fetchall()
if booked and args.remove:
    print("\nREFUSING: bookings reference slots that would be deleted:")
    for b in booked:
        print("   ", b)
    sys.exit(1)

fut = conn.execute(
    "SELECT id FROM slots WHERE vehicle_id = %s AND showroom_id = %s AND start >= now()",
    (vid, sid)).fetchall()
fut_ids = [r[0] for r in fut]
print(f"future slots to delete: {len(fut_ids)} (no bookings reference them)")

if not CONFIRM:
    print("\nDRY-RUN complete — re-run with CONFIRM=1 to apply.")
    sys.exit(0)

# ---- 1) Salesforce first (so SF never advertises what the app has dropped) -- #
DOMAIN = os.environ["SF_DOMAIN"].rstrip("/")
form = urllib.parse.urlencode({"grant_type": "client_credentials",
                               "client_id": os.environ["SF_CK"],
                               "client_secret": os.environ["SF_CS"]}).encode()
rq = urllib.request.Request(DOMAIN + "/services/oauth2/token", data=form, method="POST")
rq.add_header("Content-Type", "application/x-www-form-urlencoded")
j = json.load(urllib.request.urlopen(rq))
AT, IU = j["access_token"], j["instance_url"]


def sf(method, path, body=None):
    url = f"{IU}/services/data/{API}/{path}"
    data = json.dumps(body).encode() if body is not None else None
    r = urllib.request.Request(url, data=data, method=method)
    r.add_header("Authorization", "Bearer " + AT)
    if data is not None:
        r.add_header("Content-Type", "application/json")
    try:
        with urllib.request.urlopen(r, timeout=120) as resp:
            t = resp.read().decode()
            return resp.status, (json.loads(t) if t else None)
    except urllib.error.HTTPError as e:
        return e.code, e.read().decode()[:300]


soql = (f"SELECT Id FROM Slot__c WHERE Vehicle_Ref__r.Model_Code__c = '{args.model}' "
        f"AND Showroom_Ref__r.App_Id__c = '{sid}'")
st, d = sf("GET", "query/?q=" + urllib.parse.quote(soql))
sf_ids = [r["Id"] for r in d.get("records", [])] if st == 200 else []
print(f"Salesforce Slot__c to delete: {len(sf_ids)}")
gone = 0
for i in range(0, len(sf_ids), 200):
    st, res = sf("DELETE", "composite/sobjects?allOrNone=false&ids=" + ",".join(sf_ids[i:i + 200]))
    if st == 200:
        gone += sum(1 for x in res if x.get("success"))
print(f"  deleted {gone}/{len(sf_ids)} in Salesforce")

# ---- 2) app database -------------------------------------------------------- #
if fut_ids:
    conn.execute("DELETE FROM slots WHERE id = ANY(%s)", (fut_ids,))
conn.execute("UPDATE vehicle_models SET showroom_ids = %s WHERE id = %s",
             (json.dumps(new_sids), vid))
conn.commit()
print(f"  deleted {len(fut_ids)} app slots; showroom_ids now {new_sids}")

print(f"\nDONE at {datetime.now():%Y-%m-%d %H:%M}.")
print(f"To reverse: re-run with --add, then `python -m app.cli generate-slots --days 14 --force`.")
